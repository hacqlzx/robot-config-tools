path = r"D:\dev\code\robotConfigTools\packages\database\src\repositories\fac-info.repo.ts"
lines = []
lines.append('import Database from "better-sqlite3";')
lines.append('import { toSnake } from "../core/utils";')
lines.append('import { FacInfo, CreateFacInfoDTO, UpdateFacInfoDTO } from "../types";')
lines.append('')
lines.append('export class FacInfoRepo {')
lines.append('  constructor(private db: Database.Database) {}')
lines.append('')
lines.append('  list(): FacInfo[] {')
lines.append('    return this.db.prepare("SELECT * FROM fac_info ORDER BY sort_num").all() as FacInfo[];')
lines.append('  }')
lines.append('')
lines.append('  getById(id: number): FacInfo | undefined {')
lines.append('    return this.db.prepare("SELECT * FROM fac_info WHERE id = ?").get(id) as FacInfo | undefined;')
lines.append('  }')
lines.append('')
lines.append('  create(dto: CreateFacInfoDTO): FacInfo {')
lines.append('    const now = new Date().toISOString();')
lines.append('    const cols = "station_name, station_code, out_station_code, fac_type, station_type, province_name, city_name, area_name, create_by, create_time, update_by, update_time, volt_name, use_time, responsible_person, telephone, env_data_robot_id, current_fac, alarm_level, sort_num";')
lines.append('    const vals = "@stationName, @stationCode, @outStationCode, @facType, @stationType, @provinceName, @cityName, @areaName, @createBy, @createTime, @updateBy, @updateTime, @voltName, @useTime, @responsiblePerson, @telephone, @envDataRobotId, @currentFac, @alarmLevel, @sortNum";')
lines.append('    const stmt = this.db.prepare("INSERT INTO fac_info (" + cols + ") VALUES (" + vals + ")");')
lines.append('    const result = stmt.run({ ...dto, createTime: now, updateTime: now });')
lines.append('    return this.getById(Number(result.lastInsertRowid))!;')
lines.append('  }')
lines.append('')
lines.append('  update(id: number, dto: UpdateFacInfoDTO): void {')
lines.append('    const fields: string[] = [];')
lines.append('    const params: Record<string, any> = { id };')
lines.append('    for (const [key, value] of Object.entries(dto)) {')
lines.append('      if (value !== undefined) {')
lines.append('        fields.push(toSnake(key) + " = " + JSON.stringify(key));')
lines.append('        params[key] = value;')
lines.append('      }')
lines.append('    }')
lines.append('    if (fields.length === 0) return;')
lines.append('    fields.push("update_time = @_now");')
lines.append('    params["_now"] = new Date().toISOString();')
lines.append('    this.db.prepare("UPDATE fac_info SET " + fields.join(", ") + " WHERE id = @id").run(params);')
lines.append('  }')
lines.append('')
lines.append('  delete(id: number): void {')
lines.append('    this.db.prepare("DELETE FROM fac_info WHERE id = ?").run(id);')
lines.append('  }')
lines.append('}')
lines.append('')
with open(path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print("Written: fac-info.repo.ts")